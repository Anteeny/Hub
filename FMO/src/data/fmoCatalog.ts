const STANDARD_SIZES = ['38R', '40R', '42R', '44R', '46R', '48R', 'Custom Bespoke'];

function generateVariants(
  productId: string,
  colorName: string,
  colorHex: string,
  colorFamily: any,
  baseSku: string,
  sellingPrice: number,
  rentalPrice: number,
  costPrice: number = Math.round(sellingPrice * 0.45)
): ProductVariant[] {
  return STANDARD_SIZES.map((size, idx) => ({
    id: `${productId}-var-${idx + 1}`,
    productId,
    colorName,
    colorHex,
    colorFamily,
    size,
    sku: `${baseSku}-${size.replace(' ', '')}`,
    barcode: `FMO-${baseSku.replace(/[^A-Z0-9]/g, '')}-${idx + 101}`,
    stock: size === 'Custom Bespoke' ? 99 : Math.floor(Math.random() * 6) + 2,
    costPrice,
    sellingPrice,
    rentalPrice
  }));
}

